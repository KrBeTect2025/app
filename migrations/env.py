"""
Alembic environment: runs every time you use an `alembic` command.

Alembic manages database schema changes ("migrations") as versioned Python
files in migrations/versions/. Each file has an upgrade() (apply the change)
and a downgrade() (undo it), and points to the one before it via
down_revision, forming a chain:  d1bcefa7ceac -> 56d650961da2 -> 889f8a63bf4a

Everyday commands:

    alembic revision --autogenerate -m "what changed"   # compare models vs DB, write a new file
    alembic upgrade head                                 # apply all pending migrations
    alembic downgrade -1                                 # undo the last one
    alembic current / alembic history                    # where am I?

Always read an autogenerated file before applying it: Alembic can't detect
everything (e.g. a renamed column looks like drop + add, which loses data).
"""

import asyncio
from logging.config import fileConfig

from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from alembic import context
from sqlmodel import SQLModel
from config import db_settings

# Importing the models registers their tables in SQLModel.metadata, which
# is what --autogenerate compares the real database against.
from database.models import Shipment, Seller

# this is the Alembic Config object, which provides
# access to the values within the .ini file in use.
config = context.config

# Use the same database URL as the app (from .env), instead of
# hard-coding it in alembic.ini
config.set_main_option("sqlalchemy.url", db_settings.POSTGRES_URL)

# Interpret the config file for Python logging.
# This line sets up loggers basically.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# The "desired" schema: all tables defined with SQLModel (database/models.py)
target_metadata = SQLModel.metadata


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode (`alembic upgrade head --sql`).

    Doesn't connect to a database: it prints the SQL instead, so you can
    review it or hand it to someone who runs it on the real server.
    """
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    """Run the migrations on an open connection, inside one transaction."""
    context.configure(connection=connection, target_metadata=target_metadata)

    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    """Connect to the database with an async engine and run the migrations.

    The app uses the async driver (asyncpg), so Alembic does too. Alembic
    itself is synchronous, hence `run_sync` to call do_run_migrations.
    """

    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        # No connection pool: a migration is a one-off script
        poolclass=pool.NullPool,
    )

    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)

    await connectable.dispose()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode: against the real database."""

    asyncio.run(run_async_migrations())


# Alembic decides the mode from the command line (`--sql` = offline)
if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
